// ─────────────────────────────────────────────────────────────────────────────
// store.ts — Credential persistence layer
//
// Reads and writes login-vault.enc (encrypted JSON) in the vault root.
// Credentials are only held in plaintext while unlocked (in memory).
// ─────────────────────────────────────────────────────────────────────────────

import { App, normalizePath, TFile } from "obsidian";
import type { CredentialEntry, VaultData } from "./types";
import {
    decryptData,
    encryptData,
    hashForVerification,
} from "./crypto";

const VAULT_FILE = "login-vault.enc";

export class CredentialStore {
    private app: App;
    private credentials: CredentialEntry[] = [];
    private unlocked = false;

    constructor(app: App) {
        this.app = app;
    }

    // ── State ────────────────────────────────────────────────────────────────

    isUnlocked(): boolean {
        return this.unlocked;
    }

    async isInitialized(): Promise<boolean> {
        const file = this.app.vault.getAbstractFileByPath(normalizePath(VAULT_FILE));
        return file instanceof TFile;
    }

    // ── Initialization (first run) ────────────────────────────────────────────

    /**
   * Creates a new encrypted vault file with an empty credential list.
   * Salt is generated by the caller (auth.ts) so the derived key and vault
   * file header always share the same salt.
   */
    async initialize(key: CryptoKey, password: string, salt: string): Promise<void> {
        const verificationHash = await hashForVerification(password, salt);
        const { iv, ciphertext } = await encryptData(key, JSON.stringify([]));

        const vaultData: VaultData = {
            version: 1,
            salt,
            verificationHash,
            iv,
            ciphertext,
        };

        await this.writeVaultFile(vaultData);
        this.credentials = [];
        this.unlocked = true;
    }

    // ── Unlock ────────────────────────────────────────────────────────────────

    /**
     * Unlock using an already-verified key (password unlock derives it and
     * verifies it against the stored hash first; PIN unlock recovers it by
     * unwrapping it with a PIN-derived key). Skips password verification here
     * — decryption itself is the check: a wrong key fails the GCM auth tag.
     */
    async unlockWithKey(key: CryptoKey): Promise<boolean> {
        const vaultData = await this.readVaultFile();
        if (!vaultData) return false;

        try {
            const plaintext = await decryptData(key, vaultData.iv, vaultData.ciphertext);
            this.credentials = JSON.parse(plaintext) as CredentialEntry[];
            this.unlocked = true;
            return true;
        } catch {
            return false;
        }
    }

    // ── Lock ──────────────────────────────────────────────────────────────────

    lock(): void {
        this.credentials = [];
        this.unlocked = false;
    }

    // ── CRUD ─────────────────────────────────────────────────────────────────

    getAllCredentials(): CredentialEntry[] {
        this.assertUnlocked();
        return [...this.credentials];
    }

    getCredentialById(id: string): CredentialEntry | undefined {
        this.assertUnlocked();
        return this.credentials.find((c) => c.id === id);
    }

    async addCredential(entry: Omit<CredentialEntry, "id" | "createdAt" | "updatedAt">, key: CryptoKey): Promise<CredentialEntry> {
        this.assertUnlocked();
        const now = Date.now();
        const newEntry: CredentialEntry = {
            ...entry,
            id: this.generateId(),
            createdAt: now,
            updatedAt: now,
        };
        this.credentials.push(newEntry);
        await this.save(key);
        return newEntry;
    }

    async updateCredential(
        id: string,
        changes: Partial<Omit<CredentialEntry, "id" | "createdAt">>,
        key: CryptoKey
    ): Promise<boolean> {
        this.assertUnlocked();
        const idx = this.credentials.findIndex((c) => c.id === id);
        if (idx === -1) return false;

        this.credentials[idx] = {
            ...this.credentials[idx],
            ...changes,
            updatedAt: Date.now(),
        };
        await this.save(key);
        return true;
    }

    async deleteCredential(id: string, key: CryptoKey): Promise<boolean> {
        this.assertUnlocked();
        const before = this.credentials.length;
        this.credentials = this.credentials.filter((c) => c.id !== id);
        if (this.credentials.length === before) return false;
        await this.save(key);
        return true;
    }

    // ── Save (re-encrypt & write) ─────────────────────────────────────────────

    async save(key: CryptoKey): Promise<void> {
        this.assertUnlocked();
        const vaultData = await this.readVaultFile();
        if (!vaultData) throw new Error("Vault file not found");

        const { iv, ciphertext } = await encryptData(key, JSON.stringify(this.credentials));
        const updated: VaultData = { ...vaultData, iv, ciphertext };
        await this.writeVaultFile(updated);
    }

    // ── Change master password ────────────────────────────────────────────────

    /**
   * Re-encrypts all credentials with a new key and a new salt.
   * Both the new key and salt must be generated by the caller (auth.ts).
   */
    async changeMasterPassword(newKey: CryptoKey, newPassword: string, newSalt: string): Promise<void> {
        this.assertUnlocked();
        const oldData = await this.readVaultFile();
        if (!oldData) throw new Error("Vault file not found");

        const newHash = await hashForVerification(newPassword, newSalt);
        const { iv, ciphertext } = await encryptData(newKey, JSON.stringify(this.credentials));

        const updated: VaultData = {
            ...oldData,
            salt: newSalt,
            verificationHash: newHash,
            iv,
            ciphertext,
        };
        await this.writeVaultFile(updated);
    }

    // ── Export / Import ───────────────────────────────────────────────────────

    exportJSON(): string {
        this.assertUnlocked();
        return JSON.stringify(this.credentials, null, 2);
    }

    exportCSV(): string {
        this.assertUnlocked();
        const header = "title,username,password,url,notes,tags";
        const rows = this.credentials.map((c) => {
            const tags = (c.tags ?? []).join("|");
            return [c.title, c.username, c.password, c.url ?? "", c.notes ?? "", tags]
                .map((v) => `"${String(v).replace(/"/g, '""')}"`)
                .join(",");
        });
        return [header, ...rows].join("\n");
    }

    async importJSON(json: string, key: CryptoKey): Promise<{ added: number; skipped: number }> {
        this.assertUnlocked();
        let imported: CredentialEntry[];
        try {
            imported = JSON.parse(json) as CredentialEntry[];
        } catch {
            throw new Error("Invalid JSON file");
        }

        let added = 0;
        let skipped = 0;

        for (const entry of imported) {
            const existing = this.credentials.find((c) => c.id === entry.id);
            if (!existing) {
                this.credentials.push({ ...entry });
                added++;
            } else if (entry.updatedAt > existing.updatedAt) {
                Object.assign(existing, entry, { updatedAt: entry.updatedAt });
                added++;
            } else {
                skipped++;
            }
        }

        if (added > 0) await this.save(key);
        return { added, skipped };
    }

    // ── Helpers ───────────────────────────────────────────────────────────────

    private assertUnlocked(): void {
        if (!this.unlocked) throw new Error("Vault is locked");
    }

    private generateId(): string {
        const arr = new Uint8Array(16);
        window.crypto.getRandomValues(arr);
        return Array.from(arr, (b) => b.toString(16).padStart(2, "0")).join("");
    }

    private async readVaultFile(): Promise<VaultData | null> {
        const file = this.app.vault.getAbstractFileByPath(normalizePath(VAULT_FILE));
        if (!(file instanceof TFile)) return null;
        const raw = await this.app.vault.read(file);
        try {
            return JSON.parse(raw) as VaultData;
        } catch {
            return null;
        }
    }

    private async writeVaultFile(data: VaultData): Promise<void> {
        const path = normalizePath(VAULT_FILE);
        const json = JSON.stringify(data, null, 2);
        const file = this.app.vault.getAbstractFileByPath(path);
        if (file instanceof TFile) {
            await this.app.vault.modify(file, json);
        } else {
            await this.app.vault.create(path, json);
        }
    }
}
